/* Generates packages/runtime/src/scr_island_js.h — the C string literal
 * holding the island's JavaScript bootstrap — from the shared parts in
 * packages/runtime/src/island-js/.
 *
 * The bootstrap used to live inline in scr_island.c as a 6,400-line C
 * string literal. It is engine-agnostic JavaScript, so it now lives as
 * JavaScript: the C island embeds it through this generator, and the
 * Rust island `include_str!`s the same files directly.
 *
 * Documentation comments in the parts are BLOCK comments on their own
 * lines; the generator lifts them back out as C comments so the embedded
 * payload stays exactly the bytes the engine has always parsed — no
 * comment text ships in the binary. Run `node scripts/gen-island-
 * bootstrap.mjs` after editing any part; `--check` fails instead of
 * writing when the committed header is stale.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const partsDir = path.join(root, "packages", "runtime", "src", "island-js");
const header = path.join(root, "packages", "runtime", "src", "scr_island_js.h");

/** Escape one line of JavaScript as the body of a C string literal. */
function cEscape(line) {
  let out = "";
  for (const character of line) {
    const code = character.codePointAt(0);
    if (character === "\\") out += "\\\\";
    else if (character === '"') out += '\\"';
    else if (code < 0x20 || code === 0x7f) out += `\\x${code.toString(16).padStart(2, "0")}`;
    else out += character;
  }
  return out;
}

/** Split one part into the C comments and the payload lines, in order. */
function render(source) {
  const emitted = [];
  let inComment = false;
  for (const line of source.split("\n")) {
    if (inComment) {
      emitted.push(line);
      if (line.includes("*/")) inComment = false;
      continue;
    }
    if (line.trimStart().startsWith("/*")) {
      emitted.push(line);
      if (!line.includes("*/")) inComment = true;
      continue;
    }
    if (line === "") continue; // a blank between parts, not payload
    emitted.push(`    "${cEscape(line)}\\n"`);
  }
  if (inComment) throw new Error("unterminated block comment");
  return emitted;
}

const manifest = JSON.parse(await readFile(path.join(partsDir, "manifest.json"), "utf8"));
const body = [];
for (const file of manifest) {
  const source = await readFile(path.join(partsDir, file), "utf8");
  body.push(`    /* ── island-js/${file} ${"─".repeat(Math.max(2, 56 - file.length))} */`);
  body.push(...render(source.endsWith("\n") ? source.slice(0, -1) : source));
}

const generated = `/* GENERATED by scripts/gen-island-bootstrap.mjs from
 * packages/runtime/src/island-js/ — do not edit by hand.
 *
 * The island's JavaScript bootstrap: the CommonJS require shim over the
 * embedded module map, the Node builtin shims, and the process bridge.
 * Evaluated once at module boot; returns the CJS import helper the
 * island's boundary pins. Everything JS about the module system lives in
 * the parts — the C side only serves tables and I/O. The Rust island
 * shares the same parts through include_str!. */
#ifndef SCR_ISLAND_JS_H
#define SCR_ISLAND_JS_H

static const char isl_modules_bootstrap[] =
${body.join("\n")};

#endif /* SCR_ISLAND_JS_H */
`;

if (process.argv.includes("--check")) {
  const current = await readFile(header, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      `${path.relative(root, header)} is stale — run \`node scripts/gen-island-bootstrap.mjs\``,
    );
    process.exitCode = 1;
  } else {
    console.log(`${path.relative(root, header)} matches packages/runtime/src/island-js/.`);
  }
} else {
  await writeFile(header, generated);
  console.log(`${path.relative(root, header)}: ${body.length} lines from ${manifest.length} parts.`);
}
