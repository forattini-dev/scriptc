/* Generates the two embeddings of the island's JavaScript bootstrap from
 * the shared parts in packages/runtime/src/island-js/:
 *
 * - packages/runtime/src/scr_island_js.h, the C string literal the
 *   QuickJS island includes, holding every part;
 * - packages/runtime-rust/src/island_bootstrap.js, the subset the boa
 *   island's host bridge can serve, which that crate include_str!s.
 *
 * The bootstrap used to live inline in scr_island.c as a 6,400-line C
 * string literal. It is engine-agnostic JavaScript, so it lives as
 * JavaScript now and both islands read the same source of truth.
 *
 * Documentation in the parts is BLOCK comments on their own lines; the
 * generator lifts exactly those out — back to C comments on one side,
 * dropped on the other — so neither embedded payload carries comment
 * text. Run `node scripts/gen-island-bootstrap.mjs` after editing any
 * part; `--check` fails instead of writing when an output is stale.
 *
 * The Rust bootstrap is generated INTO the crate rather than reached
 * across packages: packages/runtime-rust publishes on its own
 * (`files: [Cargo.lock, Cargo.toml, src]`), so a cross-package
 * include_str! would resolve only by node_modules layout accident.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const partsDir = path.join(root, "packages", "runtime", "src", "island-js");
const cHeader = path.join(root, "packages", "runtime", "src", "scr_island_js.h");
const cBuiltins = path.join(root, "packages", "runtime", "src", "scr_island_builtins.h");
const rustBootstrap = path.join(root, "packages", "runtime-rust", "src", "island_bootstrap.js");
const rustBuiltins = path.join(root, "packages", "runtime-rust", "src", "island_builtin_exports.rs");

/** Escape one line of JavaScript as the body of a C string literal. */
function cEscape(line) {
  let out = "";
  for (const character of line) {
    const code = character.codePointAt(0);
    if (character === "\\") out += "\\\\";
    else if (character === '"') out += '\\"';
    else if (code < 0x20 || code === 0x7f) out += `\\x${code.toString(16).padStart(2, "0")}`;
    else out += character;
  }
  return out;
}

/**
 * Split one part into its documentation and its payload, in order.
 *
 * A documentation comment is a block comment that STARTS a line — the
 * parts' one documentation convention. Anything else, `//` comments
 * included, is payload the engine parses. Each documentation line
 * remembers the payload line it preceded, so the C side can weave it
 * back in exactly where it was written.
 */
function classify(source) {
  const documentation = [];
  const payload = [];
  let inComment = false;
  for (const line of source.replace(/\n$/, "").split("\n")) {
    if (inComment) {
      documentation.push({ at: payload.length, line });
      if (line.includes("*/")) inComment = false;
      continue;
    }
    if (line.trimStart().startsWith("/*")) {
      documentation.push({ at: payload.length, line });
      if (!line.includes("*/")) inComment = true;
      continue;
    }
    if (line === "") continue; // a blank between parts, not payload
    payload.push(line);
  }
  if (inComment) throw new Error("unterminated block comment");
  return { documentation, payload };
}

const manifest = JSON.parse(await readFile(path.join(partsDir, "manifest.json"), "utf8"));
const parts = new Map();
for (const file of new Set([...manifest.c, ...manifest.rust])) {
  parts.set(file, classify(await readFile(path.join(partsDir, file), "utf8")));
}

/* The C island: every part as one string literal, documentation lifted
 * back out to the C comments it was written as. */
const literal = [];
for (const file of manifest.c) {
  literal.push(`    /* ── island-js/${file} ${"─".repeat(Math.max(2, 56 - file.length))} */`);
  const { documentation, payload } = parts.get(file);
  let next = 0;
  for (const [index, line] of payload.entries()) {
    while (next < documentation.length && documentation[next].at === index) {
      literal.push(documentation[next].line);
      next += 1;
    }
    literal.push(`    "${cEscape(line)}\\n"`);
  }
  while (next < documentation.length) {
    literal.push(documentation[next].line);
    next += 1;
  }
}

const cSource = `/* GENERATED by scripts/gen-island-bootstrap.mjs from
 * packages/runtime/src/island-js/ — do not edit by hand.
 *
 * The island's JavaScript bootstrap: the CommonJS require shim over the
 * embedded module map, the Node builtin shims, and the process bridge.
 * Evaluated once at module boot; returns the CJS import helper the
 * island's boundary pins. Everything JS about the module system lives in
 * the parts — the C side only serves tables and I/O. */
#ifndef SCR_ISLAND_JS_H
#define SCR_ISLAND_JS_H

static const char isl_modules_bootstrap[] =
${literal.join("\n")};

#endif /* SCR_ISLAND_JS_H */
`;

/* The Rust island: the subset its host bridge can serve, as plain code. */
const rustPayload = manifest.rust.flatMap((file) => parts.get(file).payload);
const rustSource = `/* GENERATED by scripts/gen-island-bootstrap.mjs from
 * packages/runtime/src/island-js/ (the "rust" manifest) — do not edit by
 * hand, and read the PARTS, not this file: the documentation lives there
 * and is stripped here so the embedded payload is only code.
 *
 * The parts the boa island's host bridge can serve honestly:
${manifest.rust.map((file) => ` *   ${file}`).join("\n")}
 *
 * A builtin whose part is absent stays unregistered, which is the
 * island's does-not-provide throw — a fence, not a wrong answer. */
${rustPayload.join("\n")}
`;

/* ── the builtin ESM wrappers' named export lists ──────────────────── */

/* A `node:x` import LINKS against named exports, so each island needs the
 * export list of every builtin it shims. The lists are one table shared
 * by both, in builtin-exports.json; each island gets the slice its own
 * manifest actually registers, because a wrapper that destructures a name
 * from a builtin the island does not provide would fail at link instead
 * of taking the honest does-not-provide throw at evaluation. */
const exportLists = JSON.parse(await readFile(path.join(partsDir, "builtin-exports.json"), "utf8"));

/** The `node:` keys a set of parts registers on `builtins`. */
function registered(files) {
  const keys = new Set();
  for (const file of files) {
    for (const line of parts.get(file).payload) {
      // A registration, at any nesting: the http/net/tls shims sit inside
      // a block that installs them together.
      const match = /^\s+builtins(?:\.([A-Za-z_0-9]+)|\['([^']+)'\])\s*=\s*memo\(/.exec(line);
      if (match) keys.add(`node:${match[1] ?? match[2]}`);
    }
  }
  return [...keys];
}

const cShimmed = registered(manifest.c);
const missing = cShimmed.filter((key) => exportLists[key] === undefined);
if (missing.length > 0) {
  throw new Error(`builtin-exports.json has no export list for ${missing.join(", ")}`);
}

/** Wrap one export list into adjacent C string literals under 80 columns. */
function cExportLiterals(names) {
  const lines = [];
  let current = "";
  for (const [index, name] of names.entries()) {
    const piece = index === names.length - 1 ? name : `${name},`;
    if (current !== "" && current.length + piece.length > 68) {
      lines.push(current);
      current = "";
    }
    current += piece;
  }
  if (current !== "") lines.push(current);
  return lines.map((line) => `     "${line}"`).join("\n");
}

const cTable = cShimmed.map(
  (key) => `    {"${key}",\n${cExportLiterals(exportLists[key])}},`,
);

const cBuiltinsSource = `/* GENERATED by scripts/gen-island-bootstrap.mjs from
 * packages/runtime/src/island-js/builtin-exports.json — do not edit by
 * hand.
 *
 * Named export lists for the builtin ESM wrappers. The wrapper source is
 * \`const m = __scr_require("node:x"); export default m; export const
 * {…} = m;\` — the shims themselves live in the bootstrap. Only builtins
 * the island-js parts actually register appear here. */
#ifndef SCR_ISLAND_BUILTINS_H
#define SCR_ISLAND_BUILTINS_H

static const struct {
  const char *name;
  const char *exports;
} isl_builtins[] = {
${cTable.join("\n")}
};

#endif /* SCR_ISLAND_BUILTINS_H */
`;

const rustTable = registered(manifest.rust).map(
  (key) => `    ("${key}", "${exportLists[key].join(",")}"),`,
);
const rustBuiltinsSource = `/* GENERATED by scripts/gen-island-bootstrap.mjs from
 * packages/runtime/src/island-js/builtin-exports.json — do not edit by
 * hand.
 *
 * The named export lists for the builtins the Rust island's bootstrap
 * registers, so \`import { x } from "node:y"\` LINKS. A builtin outside
 * this table gets the default-only wrapper, and its require raises the
 * island's does-not-provide throw at evaluation. */

/// Named exports per shimmed builtin, mirroring the C island's
/// \`isl_builtins\`.
static ISLAND_BUILTIN_EXPORTS: [(&str, &str); ${rustTable.length}] = [
${rustTable.join("\n")}
];
`;

const outputs = [
  [cHeader, cSource, `${literal.length} lines from ${manifest.c.length} parts`],
  [cBuiltins, cBuiltinsSource, `${cTable.length} builtins`],
  [rustBootstrap, rustSource, `${rustPayload.length} lines from ${manifest.rust.length} parts`],
  [rustBuiltins, rustBuiltinsSource, `${rustTable.length} builtins`],
];

if (process.argv.includes("--check")) {
  for (const [file, generated] of outputs) {
    const current = await readFile(file, "utf8").catch(() => "");
    if (current === generated) {
      console.log(`${path.relative(root, file)} matches packages/runtime/src/island-js/.`);
    } else {
      console.error(
        `${path.relative(root, file)} is stale — run \`node scripts/gen-island-bootstrap.mjs\``,
      );
      process.exitCode = 1;
    }
  }
} else {
  for (const [file, generated, summary] of outputs) {
    await writeFile(file, generated);
    console.log(`${path.relative(root, file)}: ${summary}.`);
  }
}
