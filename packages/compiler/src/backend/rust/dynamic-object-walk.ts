import type { RustDynamicContext } from "./dynamic-context.js";
import { moduleHasLibCall } from "../../ir/ir.js";

export function emitRustDynamicObjectWalk(context: RustDynamicContext): void {
  const name = context.dynTypeName();
  const functionVariants = [...context.dynBoxedFunctionShapes]
    .flatMap((key) => {
      const shape = context.closureShapes.get(key);
      return shape === undefined ? [] : [context.dynFunctionVariant(shape)];
    })
    .filter((variant, index, variants) => variants.indexOf(variant) === index);
  const errorRoots = context.errorClassRoots();
  const classTypes = [...new Set((moduleHasLibCall(context.module(), "dyn.objectRestCheck") || moduleHasLibCall(context.module(), "dyn.objectAssignSourceCheck") || moduleHasLibCall(context.module(), "dyn.copyEnumerableSymbols") || moduleHasLibCall(context.module(), "dyn.hasSymbolKey") || moduleHasLibCall(context.module(), "dyn.defineOrdinaryData") || moduleHasLibCall(context.module(), "dyn.keyDeleteComputed") ? context.module().classes ?? [] : [])
    .filter(cls => cls.runtime !== true)
    .map(cls => context.classMetaOf(cls.name).root)
    .filter(root => !errorRoots.includes(root))
    .map(root => context.rustType({ kind: "object", className: root.def.name })))];
  context.line(`fn sc_dyn_object_data_check(value: &${name}, operation: &str) {`);
  context.pushIndent();
  context.line(`if let ${name}::Object(object) = value {`);
  context.pushIndent();
  context.line("let is_error = SC_DYN_ERROR_CACHE.with(|cache| cache.borrow().iter().any(|(_, _, cached)| cached.identity() == object.identity()));");
  context.line(`let is_class_capsule = ${classTypes.map(type => `runtime::live_dyn_ref_get::<${type}>(object.identity()).is_some()`).join(" || ") || "false"};`);
  context.line('let has_unsupported_symbols = operation == "Object.assign source" && runtime::map_has_symbol_properties(object);');
  context.line("if !is_error && !is_class_capsule && !runtime::map_is_module_namespace(object) && !runtime::map_is_proxy_restricted(object) && !has_unsupported_symbols { return; }");
  context.popIndent();
  context.line("}");
  context.line('runtime::throw_error_code(format!("scriptc SC1031: checked-dynamic {operation} requires an ordinary object without descriptor-defined properties"), "SC1031");');
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_object_rest_check(value: &${name}) { sc_dyn_object_data_check(value, "object rest"); }`);
  context.line(`fn sc_dyn_map_keys_immediate(value: ${name}) -> runtime::JsArray<${name}> { match value { ${name}::Map(map) => runtime::map_keys_to_array(&map), ${name}::Undefined => runtime::throw_type_error("Cannot read properties of undefined (reading 'keys')".into()), ${name}::Null => runtime::throw_type_error("Cannot read properties of null (reading 'keys')".into()), _ => runtime::throw_error_code("scriptc SC1031: immediate dynamic keys require a native Map".into(), "SC1031") } }`);
  context.line(`fn sc_dyn_object_assign_source_check(value: &${name}) { sc_dyn_object_data_check(value, "Object.assign source"); }`);
  context.line(`fn sc_dyn_obj_walk_push(output: &runtime::JsArray<${name}>, mode: u8, key: runtime::JsString, value: ${name}) {`);
  context.pushIndent();
  context.line("let item = match mode {");
  context.pushIndent();
  context.line(`0 => ${name}::String(key),`);
  context.line("1 => value,");
  context.line(`_ => ${name}::Array(runtime::array_new(vec![${name}::String(key), value])),`);
  context.popIndent();
  context.line("};");
  context.line("runtime::array_push(output, item);");
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_obj_walk(value: &${name}, mode: u8) -> ${name} {`);
  context.pushIndent();
  context.line(`let output: runtime::JsArray<${name}> = runtime::array_new(Vec::new());`);
  context.line("match value {");
  context.pushIndent();
  context.line(`${name}::Effect(..) => sc_dyn_effect_reflection("object reflection"),`);
  context.line(`${name}::Promise(handle) => for key in runtime::promise_handle_own_keys(handle) { let field = if mode == 0 { ${name}::Undefined } else if key == "child" { runtime::promise_handle_own_get::<runtime::JsChild>(handle, &key).map(${name}::Child).unwrap_or(${name}::Undefined) } else { runtime::throw_type_error("scriptc: Promise own property is not ported".into()) }; sc_dyn_obj_walk_push(&output, mode, runtime::string(&key), field); },`);
  context.line(`${name}::Proxy(..) => sc_dyn_proxy_unsupported("object reflection"),`);
  if (context.hasEmbeddedModules()) context.line(`${name}::Island(value) => return sc_dyn_island_object_walk(value, mode),`);
  context.line(`${name}::Undefined | ${name}::Null => runtime::throw_type_error("Cannot convert undefined or null to object".to_owned()),`);
  context.line(`${name}::Object(object) => for (key, field) in runtime::map_string_entries_js_order(object) { let field = if mode != 0 && runtime::map_is_module_namespace(object) { sc_dyn_object_key_get(object, &key, value) } else { field }; sc_dyn_obj_walk_push(&output, mode, key, field); },`);
  for (const variant of functionVariants) context.line(`${name}::${variant}(_, _, properties) => for (key, field) in runtime::map_string_entries_js_order(properties) { sc_dyn_obj_walk_push(&output, mode, key, field); },`);
  context.line(`${name}::Array(array) => {`);
  context.pushIndent();
  context.line("for key in runtime::array_own_index_keys(array) {");
  context.pushIndent();
  context.line(`let field = if mode == 0 { ${name}::Undefined } else { sc_dyn_key_get(value, &key, false) };`);
  context.line("sc_dyn_obj_walk_push(&output, mode, key, field);");
  context.popIndent();
  context.line("}");
  context.popIndent();
  context.line("},");
  context.line(`${name}::Bytes(bytes) | ${name}::Buffer(bytes) => {`);
  context.pushIndent();
  context.line("let mut index = 0usize;");
  context.line("while index < runtime::bytes_len(bytes) as usize {");
  context.pushIndent();
  context.line(`sc_dyn_obj_walk_push(&output, mode, runtime::string(&index.to_string()), ${name}::Number(runtime::bytes_get(bytes, index as f64)));`);
  context.line("index += 1;");
  context.popIndent();
  context.line("}");
  context.popIndent();
  context.line("},");
  context.line(`${name}::TypedBytes(bytes) => { let mut index = 0usize; while index < runtime::typed_bytes_len(bytes) as usize { sc_dyn_obj_walk_push(&output, mode, runtime::string(&index.to_string()), ${name}::Number(runtime::typed_bytes_get(bytes, index as f64))); index += 1; } },`);
  context.line(`${name}::String(text) => for (index, unit) in text.encode_utf16().enumerate() {`);
  context.pushIndent();
  context.line(`sc_dyn_obj_walk_push(&output, mode, runtime::string(&index.to_string()), ${name}::String(runtime::JsString::from_utf16(&[unit])));`);
  context.popIndent();
  context.line("},");
  context.line("_ => {},");
  context.popIndent();
  context.line("}");
  context.line(`${name}::Array(output)`);
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_obj_keys(value: &${name}) -> ${name} { sc_dyn_obj_walk(value, 0) }`);
  context.line(`fn sc_dyn_obj_values(value: &${name}) -> ${name} { sc_dyn_obj_walk(value, 1) }`);
  context.line(`fn sc_dyn_obj_entries(value: &${name}) -> ${name} { sc_dyn_obj_walk(value, 2) }`);
  context.line(`fn sc_dyn_has_symbol_key(value: &${name}, key: &${name}) -> bool {`);
  context.line(`let ${name}::Symbol(key) = key else { runtime::throw_type_error("scriptc: expected a symbol key".into()) };`);
  context.line(`match value { ${name}::Object(object) => { sc_dyn_object_data_check(value, "symbol presence"); runtime::map_symbol_has(object, key) }, _ => runtime::throw_error_code("scriptc SC1031: symbol presence requires an ordinary object".into(), "SC1031") }`);
  context.line("}");
  context.line(`fn sc_dyn_define_ordinary_data(target: ${name}, key: ${name}, descriptor: ${name}) -> ${name} {`);
  context.line('sc_dyn_object_data_check(&target, "dynamic property descriptor target");');
  context.line(`if !matches!(&key, ${name}::String(_) | ${name}::Symbol(_)) { runtime::throw_error_code("scriptc SC1031: dynamic property descriptor keys require a string or symbol".into(), "SC1031"); }`);
  context.line('sc_dyn_object_data_check(&descriptor, "dynamic property descriptor");');
  context.line(`for attribute in ["get", "set"] { if sc_dyn_has_own(&descriptor, &runtime::string(attribute)) { runtime::throw_error_code("scriptc SC1031: dynamic property descriptor requires writable, enumerable and configurable data".into(), "SC1031"); } }`);
  context.line(`for attribute in ["writable", "enumerable", "configurable"] { let attribute = runtime::string(attribute); if !sc_dyn_has_own(&descriptor, &attribute) || !matches!(sc_dyn_key_get(&descriptor, &attribute, false), ${name}::Boolean(true)) { runtime::throw_error_code("scriptc SC1031: dynamic property descriptor requires writable, enumerable and configurable data".into(), "SC1031"); } }`);
  context.line('let value_key = runtime::string("value");');
  context.line('if !sc_dyn_has_own(&descriptor, &value_key) { runtime::throw_error_code("scriptc SC1031: dynamic property descriptor requires an explicit value".into(), "SC1031"); }');
  context.line('let value = sc_dyn_key_get(&descriptor, &value_key, false);');
  context.line(`match key { ${name}::String(key) => { if key == "__proto__" { runtime::throw_type_error("scriptc: ordinary prototype writes are not ported".into()); } sc_dyn_key_set(&target, key, value); }, ${name}::Symbol(key) => sc_dyn_symbol_set(&target, key, value), _ => unreachable!() }`);
  context.line("target");
  context.line("}");
  context.line(`fn sc_dyn_delete_computed(target: &${name}, key: &${name}, strict: bool) -> bool {`);
  context.line(`match key { ${name}::Symbol(key) => match target {`);
  context.line(`${name}::Object(object) => { sc_dyn_object_data_check(target, "symbol deletion"); runtime::map_symbol_delete(object, key); true },`);
  context.line(`${name}::Null | ${name}::Undefined => runtime::throw_type_error("Cannot convert undefined or null to object".into()),`);
  context.line(`${name}::Number(_) | ${name}::Boolean(_) | ${name}::String(_) | ${name}::BigInt(_) | ${name}::Symbol(_) => true,`);
  context.line('_ => runtime::throw_error_code("scriptc SC1031: deleting symbol properties requires an ordinary object".into(), "SC1031"),');
  context.line('},');
  context.line(`${name}::String(_) | ${name}::Number(_) | ${name}::Boolean(_) | ${name}::BigInt(_) | ${name}::Null | ${name}::Undefined => runtime::native_delete_property(target, &sc_dyn_to_string(key), strict),`);
  context.line('_ => runtime::throw_type_error("scriptc: object string conversion requires native ToPrimitive support".into()),');
  context.line("} }");
  context.line(`fn sc_dyn_copy_enumerable_symbols(target: &${name}, source: &${name}) {`);
  context.line(`if matches!(source, ${name}::Object(..)) { sc_dyn_object_data_check(source, "symbol copy"); }`);
  context.line("let source = match source {");
  context.line(`${name}::Object(source) => source,`);
  for (const variant of functionVariants) context.line(`${name}::${variant}(_, _, properties) => properties,`);
  context.line(`${name}::Proxy(..) => return sc_dyn_proxy_unsupported("symbol copy"),`);
  context.line(`${name}::Effect(..) => return sc_dyn_effect_reflection("symbol copy"),`);
  context.line("_ => return, };");
  context.line("for (key, value) in runtime::map_symbol_entries(source) { sc_dyn_symbol_set(target, key, value); }");
  context.line("}");
  context.line(`fn sc_dyn_assign_property(target: &runtime::JsMap<runtime::JsString, ${name}>, key: runtime::JsString, value: ${name}) { if runtime::map_is_module_namespace(target) { sc_dyn_key_set(&${name}::Object(target.clone()), key, value); } else { runtime::map_set_by(target, key, value, |left, right| left.as_ref() == right.as_ref()); } }`);
  context.line(`fn sc_dyn_assign_map(target: &runtime::JsMap<runtime::JsString, ${name}>, source: &runtime::JsMap<runtime::JsString, ${name}>) {`);
  context.pushIndent();
  context.line("let mut index = 0.0;");
  context.line("while index < runtime::map_iter_count(source) {");
  context.pushIndent();
  context.line("if runtime::map_iter_live(source, index) { let key = runtime::map_iter_key(source, index); let value = runtime::map_iter_value(source, index); sc_dyn_assign_property(target, key, value); }");
  context.line("index += 1.0;");
  context.popIndent();
  context.line("}");
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_assign_from(target: &${name}, source: &${name}) {`);
  context.pushIndent();
  context.line(`if matches!(target, ${name}::Effect(..)) || matches!(source, ${name}::Effect(..)) { return sc_dyn_effect_reflection("Object.assign or object spread"); }`);
  context.line(`if matches!(target, ${name}::Proxy(..)) || matches!(source, ${name}::Proxy(..)) { return sc_dyn_proxy_unsupported("Object.assign or object spread"); }`);
  context.line("let target = match target {");
  context.pushIndent();
  context.line(`${name}::Object(target) => target,`);
  for (const variant of functionVariants) context.line(`${name}::${variant}(_, _, properties) => properties,`);
  context.line("_ => return,");
  context.popIndent();
  context.line("};");
  context.line("match source {");
  context.pushIndent();
  context.line(`${name}::Object(source) if runtime::map_is_module_namespace(source) => { let receiver = ${name}::Object(source.clone()); for (key, _) in runtime::map_string_entries_js_order(source) { let field = sc_dyn_object_key_get(source, &key, &receiver); sc_dyn_assign_property(target, key, field); } },`);
  context.line(`${name}::Object(source) => sc_dyn_assign_map(target, source),`);
  for (const variant of functionVariants) {
    context.line(`${name}::${variant}(_, _, properties) => sc_dyn_assign_map(target, properties),`);
  }
  context.line(`${name}::Array(source) => { let mut index = 0.0; while index < runtime::array_len(source) { sc_dyn_assign_property(target, runtime::string(&(index as usize).to_string()), runtime::array_get(source, index)); index += 1.0; } },`);
  context.line(`${name}::Bytes(source) => { let mut index = 0.0; while index < runtime::bytes_len(source) { sc_dyn_assign_property(target, runtime::string(&(index as usize).to_string()), ${name}::Number(runtime::bytes_get(source, index))); index += 1.0; } },`);
  context.line(`${name}::TypedBytes(source) => { let mut index = 0.0; while index < runtime::typed_bytes_len(source) { sc_dyn_assign_property(target, runtime::string(&(index as usize).to_string()), ${name}::Number(runtime::typed_bytes_get(source, index))); index += 1.0; } },`);
  context.line(`${name}::Buffer(source) => { let mut index = 0.0; while index < runtime::bytes_len(source) { sc_dyn_assign_property(target, runtime::string(&(index as usize).to_string()), ${name}::Number(runtime::bytes_get(source, index))); index += 1.0; } },`);
  context.line(`${name}::String(source) => for (index, character) in source.chars().enumerate() { sc_dyn_assign_property(target, runtime::string(&index.to_string()), ${name}::String(runtime::string(&character.to_string()))); },`);
  context.line("_ => {},");
  context.popIndent();
  context.line("}");
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_assign(target: &${name}, source: &${name}) -> ${name} {`);
  context.pushIndent();
  context.line(`if matches!(target, ${name}::Undefined | ${name}::Null) { runtime::throw_type_error("Cannot convert undefined or null to object".to_owned()); }`);
  context.line("sc_dyn_assign_from(target, source);");
  context.line("target.clone()");
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_pack_push(pack: &${name}, value: ${name}) {`);
  context.pushIndent();
  context.line(`let ${name}::Array(pack) = pack else { unreachable!("scriptc invariant: dynamic argument pack is not an array"); };`);
  context.line("runtime::array_push(pack, value);");
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_pack_push_spread(pack: &${name}, source: &${name}, what: &runtime::JsString, iterated: bool) {`);
  context.pushIndent();
  context.line("match source {");
  context.pushIndent();
  context.line(`${name}::Effect(..) => sc_dyn_effect_reflection("iteration"),`);
  context.line(`${name}::Proxy(..) => sc_dyn_proxy_unsupported("iteration"),`);
  context.line(`${name}::Array(source) => { let ${name}::Array(pack) = pack else { unreachable!() }; runtime::array_extend(pack, source); return; },`);
  context.line(`${name}::Bytes(source) => { let mut index = 0.0; while index < runtime::bytes_len(source) { sc_dyn_pack_push(pack, ${name}::Number(runtime::bytes_get(source, index))); index += 1.0; } return; },`);
  context.line(`${name}::TypedBytes(source) => { let mut index = 0.0; while index < runtime::typed_bytes_len(source) { sc_dyn_pack_push(pack, ${name}::Number(runtime::typed_bytes_get(source, index))); index += 1.0; } return; },`);
  context.line(`${name}::Buffer(source) => { let mut index = 0.0; while index < runtime::bytes_len(source) { sc_dyn_pack_push(pack, ${name}::Number(runtime::bytes_get(source, index))); index += 1.0; } return; },`);
  context.line(`${name}::String(source) => { for character in source.chars() { sc_dyn_pack_push(pack, ${name}::String(runtime::string(&character.to_string()))); } return; },`);
  context.line(`${name}::ArrayIterator(source) => { while let Some(item) = runtime::array_iterator_next(source) { let value = match item { runtime::ArrayIteratorItem::Entry(index, value) => ${name}::Array(runtime::array_new(vec![${name}::Number(index), value])), runtime::ArrayIteratorItem::Key(index) => ${name}::Number(index), runtime::ArrayIteratorItem::Value(value) => value, }; sc_dyn_pack_push(pack, value); } return; },`);
  if (context.hasEmbeddedModules()) {
    context.line(`${name}::Island(source) => { if let Some(values) = runtime::island_spread_values(source) { for value in values { sc_dyn_pack_push(pack, ${name}::Island(value)); } return; } },`);
  }
  context.line("_ => {},");
  context.popIndent();
  context.line("}");
  context.line("if !iterated {");
  context.pushIndent();
  context.line(`if matches!(source, ${name}::Undefined | ${name}::Null) { let property = if matches!(source, ${name}::Undefined) { "undefined" } else { "null" }; runtime::throw_type_error(format!("{what} is not iterable (cannot read property {property})")); }`);
  if (context.hasEmbeddedModules()) {
    context.line(`if let ${name}::Island(value) = source { let property = if runtime::island_is_undefined(value) { Some("undefined") } else if runtime::island_is_null(value) { Some("null") } else { None }; if let Some(property) = property { runtime::throw_type_error(format!("{what} is not iterable (cannot read property {property})")); } }`);
  }
  context.line('runtime::throw_type_error("Spread syntax requires ...iterable[Symbol.iterator] to be a function".to_owned());');
  context.popIndent();
  context.line("}");
  context.line("if !what.is_empty() { runtime::throw_type_error(what.to_string()); }");
  context.line("let description = match source {");
  context.pushIndent();
  context.line(`${name}::Undefined => "undefined".to_owned(),`);
  context.line(`${name}::Null => "object null".to_owned(),`);
  context.line(`${name}::Number(value) => format!("number {}", runtime::display_number(*value)),`);
  context.line(`${name}::Boolean(value) => format!("boolean {}", runtime::display_bool(*value)),`);
  context.line("value if sc_dyn_kind(value) == \"function\" => \"function\".to_owned(),");
  context.line("_ => \"object\".to_owned(),");
  context.popIndent();
  context.line("};");
  context.line("runtime::throw_type_error(format!(\"{description} is not iterable (cannot read property Symbol(Symbol.iterator))\"))");
  context.popIndent();
  context.line("}");
  context.line(`fn sc_dyn_assign_all(target: &${name}, sources: &${name}) -> ${name} {`);
  context.pushIndent();
  context.line(`if matches!(target, ${name}::Undefined | ${name}::Null) { runtime::throw_type_error("Cannot convert undefined or null to object".to_owned()); }`);
  context.line(`if matches!(target, ${name}::Effect(..)) { return sc_dyn_effect_reflection("Object.assign"); }`);
  context.line(`if matches!(target, ${name}::Proxy(..)) { return sc_dyn_proxy_unsupported("Object.assign"); }`);
  context.line(`if let ${name}::Array(sources) = sources { let mut index = 0.0; while index < runtime::array_len(sources) { let source = runtime::array_get(sources, index); sc_dyn_assign_from(target, &source); index += 1.0; } }`);
  context.line("target.clone()");
  context.popIndent();
  context.line("}");
}
