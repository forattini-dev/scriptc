export function readStable(i: number): number { return stable[i] * 1; }
export const mutable = [3, 7, 13];
export function readMutable(i: number): number { return mutable[i] * 1; }
export const escaped = [17, 19];
export function readEscaped(i: number): number { return escaped[i] * 1; }
